/** Generates docs/FONTS.md and copies each font package's LICENSE file, from the registry + node_modules metadata. */
import fs from "node:fs";
import path from "node:path";
import { FONT_OPTIONS } from "../src/remotion/fontStacks";

const outDir = path.resolve("docs/licenses/fonts");
fs.mkdirSync(outDir, { recursive: true });
const rows: string[] = [];
const seen = new Set<string>();
for (const f of FONT_OPTIONS) {
  const pkgDir = path.resolve("node_modules", f.source);
  const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8"));
  const licFile = ["LICENSE", "LICENSE.txt", "LICENSE.md"].map((n) => path.join(pkgDir, n)).find((p) => fs.existsSync(p));
  let copyright = "(see licence file)";
  if (licFile) {
    const first = fs.readFileSync(licFile, "utf8").split("\n").find((l) => /copyright/i.test(l));
    if (first) copyright = first.replace(/\s+/g, " ").trim().slice(0, 140);
    const dest = path.join(outDir, `${f.source.replace("@fontsource/", "")}.LICENSE.txt`);
    if (!seen.has(dest)) { fs.copyFileSync(licFile, dest); seen.add(dest); }
  }
  rows.push(`| ${f.label} | ${f.scripts.join(", ")} | ${f.weights.join(", ")} | ${pkg.license} (${f.license}) | \`${f.source}@${pkg.version}\` | ${copyright.replace(/\|/g, "/")} |`);
}
const md = `# Fonts and licences

Generated by \`npx tsx scripts/font-licenses.ts\` from the font registry (\`src/remotion/fontStacks.ts\`) and each package's own \`package.json\`.
Licence texts are copied to \`docs/licenses/fonts/\`.

All fonts are shipped **unmodified** through [Fontsource](https://fontsource.org) npm packages and bundled locally - nothing is fetched from Google Fonts or any CDN at preview or render time, so exported MP4s are reproducible offline.

| Font | Scripts | Weights bundled | Licence (package / registry) | Package | Copyright line |
|---|---|---|---|---|---|
${rows.join("\n")}

## What the licences require (summary, not legal advice)

* **SIL Open Font License 1.1 (OFL)**: the fonts may be used, embedded and redistributed (including inside rendered videos) for any purpose, commercial included; they may not be *sold on their own*; modified versions may not use the Reserved Font Name; the licence text and copyright must accompany redistributed copies of the font files. This repo does not modify any font and ships the licence files in \`docs/licenses/fonts/\`. Text rendered into a video is not a redistribution of the font software.
* **Apache-2.0** (Permanent Marker): permissive; keep the licence text and notices when redistributing the font files (done).
* The Malayalam, Devanagari and Tamil faces (Noto Sans family, Anek Malayalam) are OFL-1.1 and are the fallback for every font stack, so Indic text always has glyph coverage.

## Font engine features

Automatic loading (\`@font-face\` bundled via Fontsource CSS, plus \`document.fonts.load\` gating of every caption group / text layer, which also holds the Remotion render until the face is ready), per-glyph fallback chain ending in Noto Malayalam/Devanagari/Tamil, size, weight, letter-spacing (skipped automatically for Indic scripts), line-height, stroke width and colour (drawn outside the glyph via \`paint-order\`), text shadow, text transform (none/upper/lower/capitalise, skipped for Indic scripts), background highlights/pills/boxes and responsive line wrapping (balanced line breaking + measured fit-to-width).
`;
fs.writeFileSync("docs/FONTS.md", md);
console.log(`wrote docs/FONTS.md (${rows.length} fonts)`);
