/**
 * SEO health audit.
 *
 *   npm run seo:audit                         static checks on the SEO data and sitemaps (no server needed)
 *   npm run seo:audit -- --live http://localhost:3000    also fetches every sitemap URL from a running site
 *   npm run seo:audit -- --map                print the keyword map as markdown (add --write to save docs/seo-keyword-map.md)
 *
 * Exits with an error code when an error is found. Warnings do not fail the run.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { TEMPLATES } from "../../src/data/templates";
import { SUPPORT_EMAIL, SUPPORT_WHATSAPP } from "../../src/config/site";
import { linksIn } from "../../src/components/seo/RichText";
import robots from "../../src/app/robots";
import { fileExistsInPublic, pageVerdict, templateVerdict } from "../../src/seo/indexable";
import { templateDescription, templateImage, templateTitle } from "../../src/seo/metadata";
import { ALL_PAGES, getPageByPath, pageTemplates } from "../../src/seo/select";
import { entriesFor, SITEMAP_NAMES } from "../../src/seo/sitemap";
import { FEATURE_SCREENSHOTS } from "../../src/seo/screenshots";
import { canonicalPath, canonicalUrl, SEO_ORIGIN } from "../../src/seo/url";

const args = process.argv.slice(2);
const liveBase = args.includes("--live") ? args[args.indexOf("--live") + 1] : undefined;

type Finding = { level: "error" | "warn"; where: string; msg: string };
const out: Finding[] = [];
const err = (where: string, msg: string) => out.push({ level: "error", where, msg });
const warn = (where: string, msg: string) => out.push({ level: "warn", where, msg });

/* ------------------------------------------------------------------ keyword map */
if (args.includes("--map")) {
  const cell = (x: string) => x.replace(/\|/g, "\\|");
  const rows = ALL_PAGES.map((p) => {
    const v = pageVerdict(p, pageTemplates(p).length);
    return `| ${[p.path, p.primaryKeyword, p.secondaryKeywords.join(", ") || "none", p.searchIntent, p.type, p.title, p.h1, p.related.join(" ") || "none", pageTemplates(p).map((t) => t.slug).join(", ") || "none", v.indexable ? "index" : "noindex: " + v.reasons.join("; ")].map(cell).join(" | ")} |`;
  });
  const md = ["# SEO keyword map", "", "Generated by `npm run seo:audit -- --map --write` from src/seo/pages.ts and src/seo/guides.ts. One primary keyword per page; no two pages share one.", "", "| Page | Primary keyword | Secondary keywords | Search intent | Type | Title | H1 | Related pages | Templates shown | Indexing |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |", ...rows, ""].join("\n");
  if (args.includes("--write")) {
    mkdirSync(join(process.cwd(), "docs"), { recursive: true });
    writeFileSync(join(process.cwd(), "docs", "seo-keyword-map.md"), md);
    console.log("Wrote docs/seo-keyword-map.md");
  } else console.log(md);
  process.exit(0);
}

/* ------------------------------------------------------------------ static checks */
const dupes = (label: string, values: [string, string][]) => {
  const seen = new Map<string, string>();
  for (const [where, v] of values) {
    const k = v.trim().toLowerCase();
    if (!k) continue;
    if (seen.has(k)) err(where, `duplicate ${label} with ${seen.get(k)}: "${v}"`);
    else seen.set(k, where);
  }
};

const pageRows = ALL_PAGES.map((p) => ({ p, where: p.path }));
const tplPaths = new Set(TEMPLATES.map((t) => `/templates/${t.slug}`));
const known = new Set<string>(["/", "/create", ...ALL_PAGES.map((p) => p.path), ...tplPaths]);
const resolves = (href: string) => known.has(canonicalPath(href)) || canonicalPath(href) === "/";

for (const { p, where } of pageRows) {
  if (!p.title) err(where, "missing title");
  else {
    if (p.title.length > 70) err(where, `title is ${p.title.length} characters`);
    else if (p.title.length > 62) warn(where, `title is ${p.title.length} characters, may be cut in results`);
  }
  if (!p.description) err(where, "missing description");
  else if (p.description.length > 165) warn(where, `description is ${p.description.length} characters`);
  else if (p.description.length < 70) warn(where, `description is short (${p.description.length})`);
  if (!p.h1) err(where, "missing H1");
  if (p.type !== "home" && !p.path.startsWith("/")) err(where, "path does not start with /");
  if (p.path !== "/" && p.path.endsWith("/")) err(where, "path ends with a slash");
  for (const r of p.related) if (!getPageByPath(r)) err(where, `related page does not exist: ${r}`);
  for (const s of p.sections) for (const text of [...s.body, ...(s.bullets ?? [])]) for (const href of linksIn(text)) if (!resolves(href)) err(where, `broken internal link in copy: ${href}`);
  for (const c of p.crumbs) if (!resolves(c.href)) err(where, `breadcrumb points nowhere: ${c.href}`);
  const v = pageVerdict(p, pageTemplates(p).length);
  if (!v.indexable && p.id !== "contact") warn(where, `will be noindex: ${v.reasons.join("; ")}`);
}
dupes("title", pageRows.map(({ p, where }) => [where, p.title]));
dupes("description", pageRows.map(({ p, where }) => [where, p.description]));
dupes("H1", pageRows.map(({ p, where }) => [where, p.h1]));
dupes("canonical", pageRows.map(({ p, where }) => [where, canonicalUrl(p.path)]));
dupes("primary keyword (cannibalization)", pageRows.map(({ p, where }) => [where, p.primaryKeyword]));

/* templates */
for (const t of TEMPLATES) {
  const where = `/templates/${t.slug}`;
  if (!templateTitle(t.slug)) err(where, "no SEO title");
  if (templateTitle(t.slug).length > 70) warn(where, `title is ${templateTitle(t.slug).length} characters`);
  const d = templateDescription(t.slug);
  if (!d) err(where, "no description");
  else if (d.length > 165) warn(where, `description is ${d.length} characters`);
  if (!templateImage(t.slug).alt) err(where, "image without alt text");
  for (const f of [`/thumbs/${t.slug}.webp`, `/renders/${t.slug}.webp`]) if (!fileExistsInPublic(f)) err(where, `missing image ${f}`);
  const v = templateVerdict(t);
  if (!v.indexable) warn(where, `will be noindex: ${v.reasons.join("; ")}`);
}
dupes("template title", TEMPLATES.map((t) => [`/templates/${t.slug}`, templateTitle(t.slug)]));
dupes("template description", TEMPLATES.map((t) => [`/templates/${t.slug}`, templateDescription(t.slug)]));

/* feature screenshots */
for (const [feature, shots] of Object.entries(FEATURE_SCREENSHOTS)) for (const s of shots ?? []) {
  if (!existsSync(join(process.cwd(), "public", s.src))) err(`/features/${feature}`, `missing screenshot ${s.src}`);
  if (!s.alt) err(`/features/${feature}`, `screenshot without alt: ${s.src}`);
}

/* sitemaps: every URL canonical, indexable, unique, and not blocked by robots.txt */
const rules = robots().rules;
const disallow = (Array.isArray(rules) ? rules : [rules]).flatMap((r) => (typeof r.disallow === "string" ? [r.disallow] : r.disallow ?? []));
const seenUrls = new Set<string>();
for (const name of SITEMAP_NAMES) {
  for (const e of entriesFor(name)) {
    if (seenUrls.has(e.loc)) err(`sitemap-${name}`, `URL listed twice: ${e.loc}`);
    seenUrls.add(e.loc);
    const path = canonicalPath(e.loc);
    if (e.loc !== canonicalUrl(path)) err(`sitemap-${name}`, `not a canonical URL: ${e.loc}`);
    if (e.loc.includes("?") || e.loc.includes("#")) err(`sitemap-${name}`, `has a query string or fragment: ${e.loc}`);
    if (disallow.some((d) => path.startsWith(d.replace(/\/$/, "")) && d !== "/")) err(`sitemap-${name}`, `blocked by robots.txt: ${path}`);
    if (!e.loc.startsWith(SEO_ORIGIN)) err(`sitemap-${name}`, `wrong origin: ${e.loc}`);
    const page = getPageByPath(path);
    if (page && !pageVerdict(page, pageTemplates(page).length).indexable) err(`sitemap-${name}`, `noindex page is listed: ${path}`);
  }
}
if (disallow.includes("/i/")) err("robots.txt", "/i/ is blocked, which hides its noindex tag from crawlers");

/* environment */
if (!SEO_ORIGIN.startsWith("https://www.yourein.in")) warn("environment", `canonical origin is ${SEO_ORIGIN}; production should be https://www.yourein.in (set NEXT_PUBLIC_SITE_URL)`);
if (!SUPPORT_EMAIL && !SUPPORT_WHATSAPP) warn("environment", "no support contact configured: /contact is noindex and shows no way to reach you (set NEXT_PUBLIC_SUPPORT_EMAIL)");
if (!process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION) warn("environment", "NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION is not set (needed only for the HTML-tag verification method)");

/* ------------------------------------------------------------------ live checks */
async function live(base: string) {
  const urls = [...seenUrls].map((u) => u.replace(SEO_ORIGIN, base.replace(/\/$/, "")));
  for (const [i, url] of urls.entries()) {
    const path = canonicalPath(url);
    let res: Response;
    try {
      res = await fetch(url, { redirect: "manual" });
    } catch (e) {
      err(path, `could not fetch: ${(e as Error).message}`);
      continue;
    }
    if (res.status !== 200) {
      err(path, `status ${res.status}`);
      continue;
    }
    const html = await res.text();
    const titles = html.match(/<title>[^<]*<\/title>/g) ?? [];
    if (titles.length !== 1) err(path, `${titles.length} <title> tags`);
    const h1s = html.match(/<h1[\s>]/g) ?? [];
    if (h1s.length !== 1) err(path, `${h1s.length} <h1> elements`);
    if (!/<meta name="description" content="[^"]+"/.test(html)) err(path, "missing meta description");
    const canon = html.match(/<link rel="canonical" href="([^"]+)"/);
    if (!canon) err(path, "missing canonical");
    else if (canonicalPath(canon[1]) !== path) err(path, `canonical points elsewhere: ${canon[1]}`);
    if (/<meta name="robots" content="[^"]*noindex/.test(html)) err(path, "unexpected noindex on a sitemap URL");
    if (!/<meta property="og:image" content="[^"]+"/.test(html)) err(path, "missing og:image");
    const imgs = html.match(/<img\b[^>]*>/g) ?? [];
    const noAlt = imgs.filter((t) => !/\balt="/.test(t));
    if (noAlt.length) err(path, `${noAlt.length} image(s) without alt text`);
    for (const block of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
      try {
        const data = JSON.parse(block[1]);
        const text = JSON.stringify(data);
        if (/AggregateRating|"Review"|ratingValue/.test(text)) err(path, "structured data contains ratings or reviews");
      } catch {
        err(path, "structured data is not valid JSON");
      }
    }
    if (!/application\/ld\+json/.test(html)) warn(path, "no structured data");
    const links = [...html.matchAll(/<a [^>]*href="(\/[^"#?]*)/g)].map((m) => canonicalPath(m[1]));
    const broken = new Set<string>();
    for (const l of new Set(links)) if (!resolves(l) && !/^\/(start|signin|dashboard|api|_next|i|shot|invites|guests|account|edit|pay|success|reset|templates)\b/.test(l) && !/\.[a-z0-9]+$/i.test(l)) broken.add(l);
    for (const b of broken) err(path, `link to an unknown page: ${b}`);
    if (i % 10 === 9) process.stdout.write(".");
  }
  process.stdout.write("\n");
  /* robots + noindex on guest invitations */
  const r = await fetch(`${base}/robots.txt`).then((x) => x.text());
  if (!/Sitemap: /.test(r)) err("robots.txt", "no Sitemap line");
  if (/Disallow: \/i\//.test(r)) err("robots.txt", "/i/ is blocked");
  for (const n of SITEMAP_NAMES) {
    const x = await fetch(`${base}/sitemap-${n}.xml`);
    if (x.status !== 200 && entriesFor(n).length) err(`sitemap-${n}.xml`, `status ${x.status}`);
  }
}

(async () => {
  if (liveBase) {
    console.log(`Fetching ${seenUrls.size} sitemap URLs from ${liveBase}`);
    await live(liveBase);
  }
  const errors = out.filter((f) => f.level === "error");
  const warnings = out.filter((f) => f.level === "warn");
  for (const f of out) console.log(`${f.level === "error" ? "ERROR" : "warn "}  ${f.where}  ${f.msg}`);
  console.log(`\n${ALL_PAGES.length} landing pages, ${TEMPLATES.length} templates, ${seenUrls.size} sitemap URLs. ${errors.length} error(s), ${warnings.length} warning(s).`);
  process.exit(errors.length ? 1 : 0);
})();
